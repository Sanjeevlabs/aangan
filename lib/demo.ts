function lcgPeaks(seed: number, n = 48): number[] {
  let s = seed;
  const out: number[] = [];
  for (let i = 0; i < n; i++) {
    s = (s * 1103515245 + 12345) & 0x7fffffff;
    const wave = 0.35 + 0.3 * Math.sin(i / 4);
    out.push(Math.min(1, Math.max(0.08, wave + (s % 1000) / 1000 / 2)));
  }
  return out.map((v) => Math.round(v * 100) / 100);
}

